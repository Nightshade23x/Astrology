def fill_missing_dobs(
    limit,
):

    # Generated player information.
    players = pd.read_csv(
        PLAYERS_PATH
    )

    # Persistent DOB/zodiac database.
    enrichment = load_enrichment()

    missing_ids = set(
        enrichment[
            enrichment["birth_date"].isna()
        ]["player_id"]
    )

    missing = players[
        players["player_id"].isin(
            missing_ids
        )
    ].copy()

    # -----------------------------------------------------
    # PRIORITISE PLAYERS
    # -----------------------------------------------------

    # Players never previously attempted should come
    # before old unresolved cases.
    previously_attempted = set()

    if LOOKUP_LOG_PATH.exists():

        old_log = pd.read_csv(
            LOOKUP_LOG_PATH
        )

        previously_attempted = set(
            old_log[
                "player_id"
            ].dropna().astype(int)
        )

    missing[
        "previously_attempted"
    ] = missing[
        "player_id"
    ].isin(
        previously_attempted
    )

    missing = missing.sort_values(
        [
            "previously_attempted",
            "appearances",
        ],
        ascending=[
            True,
            False,
        ],
    )

    if limit is not None:
        missing = missing.head(
            limit
        )

    print(
        f"Players currently missing DOB: "
        f"{len(missing_ids)}"
    )

    print(
        f"Players selected this run: "
        f"{len(missing)}"
    )

    results = []

    matched_count = 0

    # -----------------------------------------------------
    # LOOKUPS
    # -----------------------------------------------------

    for number, (
        _,
        row,
    ) in enumerate(
        missing.iterrows(),
        start=1,
    ):

        player_id = int(
            row["player_id"]
        )

        player_name = row[
            "player_name"
        ]

        print(
            f"[{number}/{len(missing)}] "
            f"{player_name} "
            f"(ID {player_id})"
        )

        try:

            result = process_player(
                player_id,
                player_name,
            )

            status = result[
                "status"
            ]

            print(
                f"    -> {status}"
            )

            if status == "matched":

                updated = (
                    update_enrichment(
                        enrichment,
                        player_id,
                        result[
                            "birth_date"
                        ],
                        result[
                            "qid"
                        ],
                    )
                )

                if updated:

                    matched_count += 1

                    print(
                        f"       "
                        f"{result['birth_date']} "
                        f"({result['qid']})"
                    )

            results.append(
                {
                    "player_id":
                        player_id,

                    "player_name":
                        player_name,

                    "status":
                        status,

                    "qid":
                        result["qid"],

                    "candidate_label":
                        result[
                            "candidate_label"
                        ],

                    "similarity":
                        result[
                            "similarity"
                        ],

                    "birth_date":
                        result[
                            "birth_date"
                        ],
                }
            )

        except Exception as exc:

            print(
                f"    -> error: {exc}"
            )

            results.append(
                {
                    "player_id":
                        player_id,

                    "player_name":
                        player_name,

                    "status":
                        "error",

                    "qid":
                        None,

                    "candidate_label":
                        None,

                    "similarity":
                        None,

                    "birth_date":
                        None,
                }
            )

    # -----------------------------------------------------
    # SAVE
    # -----------------------------------------------------

    save_enrichment(
        enrichment
    )

    save_log(
        results
    )

    # -----------------------------------------------------
    # SUMMARY
    # -----------------------------------------------------

    total = len(
        enrichment
    )

    with_dob = (
        enrichment[
            "birth_date"
        ]
        .notna()
        .sum()
    )

    print("\n==============================")
    print("WIKIDATA LOOKUP SUMMARY")
    print("==============================")

    if results:

        result_df = pd.DataFrame(
            results
        )

        print(
            result_df[
                "status"
            ]
            .value_counts(
                dropna=False
            )
            .to_string()
        )

        print()

    print(
        f"New DOBs added: "
        f"{matched_count}"
    )

    print(
        f"Total DOB coverage: "
        f"{with_dob}/{total}"
    )

    print(
        f"Still missing: "
        f"{total - with_dob}"
    )

    print("==============================\n")


# ---------------------------------------------------------
# CLI
# ---------------------------------------------------------

def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--limit",
        type=int,
        default=25,
        help=(
            "Maximum number of missing players "
            "to attempt in this run."
        ),
    )

    args = parser.parse_args()

    fill_missing_dobs(
        limit=args.limit
    )


if __name__ == "__main__":
    main()