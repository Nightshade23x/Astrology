def cache_path(player_id):

    return (
        RAW_DIR
        / f"player_{int(player_id)}.json"
    )


def load_cache(player_id):

    path = cache_path(
        player_id
    )

    if not path.exists():
        return None

    try:

        with open(
            path,
            "r",
            encoding="utf-8",
        ) as file:

            payload = json.load(
                file
            )

        # Only use cache generated by
        # this version of the script.
        if (
            isinstance(payload, dict)
            and payload.get(
                "cache_version"
            ) == 2
        ):
            return payload

    except Exception:
        pass

    return None


def save_cache(
    player_id,
    payload,
):

    path = cache_path(
        player_id
    )

    payload[
        "cache_version"
    ] = 2

    with open(
        path,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            payload,
            file,
            indent=2,
            ensure_ascii=False,
        )


# ---------------------------------------------------------
# NAME NORMALISATION
# ---------------------------------------------------------

def normalise_name(value):

    if value is None:
        return ""

    value = str(value)

    value = unicodedata.normalize(
        "NFKD",
        value,
    )

    value = "".join(
        char
        for char in value
        if not unicodedata.combining(
            char
        )
    )

    value = value.lower()

    value = re.sub(
        r"[^a-z0-9 ]+",
        " ",
        value,
    )

    value = re.sub(
        r"\s+",
        " ",
        value,
    )

    return value.strip()


def name_similarity(
    player_name,
    candidate_name,
):

    player = normalise_name(
        player_name
    )

    candidate = normalise_name(
        candidate_name
    )

    if not player or not candidate:
        return 0

    if player == candidate:
        return 100

    player_tokens = (
        player.split()
    )

    candidate_tokens = (
        candidate.split()
    )

    # Useful for names where Wikidata
    # contains an additional middle name.
    if (
        len(player_tokens) >= 2
        and all(
            token in candidate_tokens
            for token in player_tokens
        )
    ):
        return 94

    score = SequenceMatcher(
        None,
        player,
        candidate,
    ).ratio()

    return round(
        score * 100,
        2,
    )


