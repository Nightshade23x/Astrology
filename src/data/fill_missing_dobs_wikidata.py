def create_session():

    session = requests.Session()

    retries = Retry(
        total=5,
        backoff_factor=1.0,
        status_forcelist=[
            429,
            500,
            502,
            503,
            504,
        ],
        allowed_methods=["GET"],
    )

    adapter = HTTPAdapter(
        max_retries=retries
    )

    session.mount(
        "https://",
        adapter,
    )

    session.headers.update(
        {
            "User-Agent":
                "EPL-Zodiac-Thesis/1.0 "
                "(University research project)"
        }
    )

    return session


SESSION = create_session()


