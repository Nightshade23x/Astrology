def wikidata_request(params):

    response = SESSION.get(
        WIKIDATA_API,
        params=params,
        timeout=30,
    )

    response.raise_for_status()

    return response.json()


def search_wikidata(
    player_name,
):

    params = {
        "action":
            "wbsearchentities",

        "format":
            "json",

        "language":
            "en",

        "uselang":
            "en",

        "type":
            "item",

        "limit":
            10,

        "search":
            player_name,
    }

    return wikidata_request(
        params
    )


def fetch_entity(qid):

    params = {
        "action":
            "wbgetentities",

        "format":
            "json",

        "ids":
            qid,

        "props":
            "claims|labels|descriptions",

        "languages":
            "en",
    }

    return wikidata_request(
        params
    )


# ---------------------------------------------------------
# FOOTBALL CANDIDATES
# ---------------------------------------------------------

def is_football_candidate(
    result,
):

    description = (
        result.get(
            "description"
        )
        or ""
    ).lower()

    return any(
        term in description
        for term in FOOTBALL_TERMS
    )


def choose_candidate(
    player_name,
    search_payload,
):

    # Single-name players are too risky
    # for automatic Wikidata matching.
    if len(
        normalise_name(
            player_name
        ).split()
    ) == 1:

        return (
            None,
            "single_name_manual_review",
            [],
        )

    search_results = (
        search_payload.get(
            "search",
            []
        )
    )

    candidates = []

    for result in search_results:

        if not is_football_candidate(
            result
        ):
            continue

        label = result.get(
            "label",
            ""
        )

        score = name_similarity(
            player_name,
            label,
        )

        candidates.append(
            {
                "qid":
                    result.get("id"),

                "label":
                    label,

                "description":
                    result.get(
                        "description"
                    ),

                "score":
                    score,
            }
        )

    candidates = sorted(
        candidates,
        key=lambda item:
            item["score"],
        reverse=True,
    )

    if not candidates:

        return (
            None,
            "no_confident_football_candidate",
            candidates,
        )

    best = candidates[0]

    # Minimum acceptable similarity.
    if best["score"] < 90:

        return (
            None,
            "no_confident_football_candidate",
            candidates,
        )

    # If multiple football candidates
    # exist, demand a very strong winner.
    if len(candidates) > 1:

        second = candidates[1]

        margin = (
            best["score"]
            - second["score"]
        )

        if (
            best["score"] < 95
            or margin < 8
        ):

            return (
                None,
                "ambiguous_candidates",
                candidates,
            )

    return (
        best,
        "candidate_selected",
        candidates,
    )


# ---------------------------------------------------------
# BIRTH DATE EXTRACTION
# ---------------------------------------------------------

def extract_birth_date(
    entity_payload,
    qid,
):

    entities = entity_payload.get(
        "entities",
        {}
    )

    entity = entities.get(
        qid,
        {}
    )

    claims = entity.get(
        "claims",
        {}
    )

    birth_claims = claims.get(
        "P569",
        []
    )

    if not birth_claims:
        return (
            None,
            "no_birth_date",
        )

    for claim in birth_claims:

        mainsnak = claim.get(
            "mainsnak",
            {}
        )

        datavalue = mainsnak.get(
            "datavalue",
            {}
        )

        value = datavalue.get(
            "value"
        )

        if not isinstance(
            value,
            dict,
        ):
            continue

        precision = value.get(
            "precision"
        )

        # Wikidata precision:
        # 11 = exact day
        if (
            precision is None
            or precision < 11
        ):
            continue

        time_value = value.get(
            "time"
        )

        if not time_value:
            continue

        # Example:
        # +1995-09-24T00:00:00Z
        match = re.match(
            r"^[+-](\d{4})-(\d{2})-(\d{2})T",
            time_value,
        )

        if not match:
            continue

        year, month, day = (
            match.groups()
        )

        birth_date = (
            f"{year}-"
            f"{month}-"
            f"{day}"
        )

        return (
            birth_date,
            "matched",
        )

    return (
        None,
        "insufficient_date_precision",
    )


# ---------------------------------------------------------
# LOOKUP LOG
# ---------------------------------------------------------

def save_log(results):

    if not results:
        return

    new_df = pd.DataFrame(
        results
    )

    if LOOKUP_LOG_PATH.exists():

        old_df = pd.read_csv(
            LOOKUP_LOG_PATH
        )

        combined = pd.concat(
            [
                old_df,
                new_df,
            ],
            ignore_index=True,
        )

        combined = (
            combined
            .drop_duplicates(
                subset=[
                    "player_id"
                ],
                keep="last",
            )
        )

    else:

        combined = new_df

    combined = combined.sort_values(
        "player_id"
    )

    combined.to_csv(
        LOOKUP_LOG_PATH,
        index=False,
        encoding="utf-8",
    )


# ---------------------------------------------------------
# UPDATE ENRICHMENT
# ---------------------------------------------------------

def update_enrichment(
    enrichment,
    player_id,
    birth_date,
    qid,
):

    matching_rows = enrichment[
        enrichment["player_id"]
        == int(player_id)
    ].index

    if len(matching_rows) != 1:
        return False

    index = matching_rows[0]

    # Never overwrite an existing DOB.
    if pd.notna(
        enrichment.at[
            index,
            "birth_date"
        ]
    ):
        return False

    enrichment.at[
        index,
        "birth_date"
    ] = birth_date

    enrichment.at[
        index,
        "zodiac"
    ] = zodiac_from_date(
        birth_date
    )

    enrichment.at[
        index,
        "dob_source"
    ] = f"Wikidata:{qid}"

    # Automatically matched,
    # therefore not independently verified.
    enrichment.at[
        index,
        "dob_verified"
    ] = False

    return True


# ---------------------------------------------------------
# PROCESS PLAYER
# ---------------------------------------------------------

def process_player(
    player_id,
    player_name,
):

    cached = load_cache(
        player_id
    )

    if cached is not None:

        search_payload = cached.get(
            "search_payload",
            {}
        )

    else:

        search_payload = (
            search_wikidata(
                player_name
            )
        )

        cached = {
            "player_id":
                int(player_id),

            "player_name":
                player_name,

            "search_payload":
                search_payload,
        }

        save_cache(
            player_id,
            cached,
        )

        # Be polite to Wikidata.
        time.sleep(0.25)

    candidate, status, candidates = (
        choose_candidate(
            player_name,
            search_payload,
        )
    )

    if candidate is None:

        return {
            "status":
                status,

            "qid":
                None,

            "candidate_label":
                None,

            "similarity":
                None,

            "birth_date":
                None,

            "candidates":
                candidates,
        }

    qid = candidate[
        "qid"
    ]

    # -----------------------------------------------------
    # ENTITY DATA
    # -----------------------------------------------------

    entity_payload = cached.get(
        "entity_payload"
    )

    cached_qid = cached.get(
        "entity_qid"
    )

    if (
        entity_payload is None
        or cached_qid != qid
    ):

        entity_payload = fetch_entity(
            qid
        )

        cached[
            "entity_qid"
        ] = qid

        cached[
            "entity_payload"
        ] = entity_payload

        save_cache(
            player_id,
            cached,
        )

        time.sleep(0.25)

    birth_date, birth_status = (
        extract_birth_date(
            entity_payload,
            qid,
        )
    )

    return {
        "status":
            birth_status,

        "qid":
            qid,

        "candidate_label":
            candidate["label"],

        "similarity":
            candidate["score"],

        "birth_date":
            birth_date,

        "candidates":
            candidates,
    }


